BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS app;

-- Domain 1 owns users; Domain 2 owns integer-keyed jobs. Applications are
-- introduced here as the shared M4 feature table and reference both owners.
ALTER TABLE public.jobs
  ADD COLUMN IF NOT EXISTS recruiter_id bigint REFERENCES public.users(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS public.applications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  job_id integer NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
  applicant_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  resume_version_id uuid REFERENCES public.resume_versions(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'applied'
    CHECK (status IN ('saved','applied','shortlisted','interview','rejected')),
  resume_score numeric(6,2),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (job_id, applicant_id)
);

ALTER TABLE public.applications
  ADD COLUMN IF NOT EXISTS resume_version_id uuid REFERENCES public.resume_versions(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS applications_resume_version_idx ON public.applications (resume_version_id, created_at DESC);

CREATE TABLE IF NOT EXISTS app.notification (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  type text NOT NULL CHECK (type IN ('application_status','job_match','message','system','high_match','low_competition','startup_hiring','instant_job')),
  title text NOT NULL CHECK (char_length(title) <= 180),
  body text NOT NULL CHECK (char_length(body) <= 4000),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  read_at timestamptz,
  delivered_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz
);
ALTER TABLE app.notification DROP CONSTRAINT IF EXISTS notification_type_check;
ALTER TABLE app.notification ADD CONSTRAINT notification_type_check
  CHECK (type IN ('application_status','job_match','message','system','high_match','low_competition','startup_hiring','instant_job'));

CREATE TABLE IF NOT EXISTS app.alert_preference (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  alert_type text NOT NULL CHECK (alert_type IN ('application_status','job_match','message','system','high_match','low_competition','startup_hiring','instant_job')),
  channel text NOT NULL CHECK (channel IN ('in_app','email','push')),
  enabled boolean NOT NULL DEFAULT true,
  match_threshold numeric(5,2) CHECK (match_threshold IS NULL OR match_threshold BETWEEN 0 AND 100),
  quiet_start time,
  quiet_end time,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, alert_type, channel),
  CHECK ((quiet_start IS NULL) = (quiet_end IS NULL))
);
ALTER TABLE app.alert_preference DROP CONSTRAINT IF EXISTS alert_preference_alert_type_check;
ALTER TABLE app.alert_preference ADD CONSTRAINT alert_preference_alert_type_check
  CHECK (alert_type IN ('application_status','job_match','message','system','high_match','low_competition','startup_hiring','instant_job'));
ALTER TABLE app.alert_preference
  ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE app.alert_preference
  ADD COLUMN IF NOT EXISTS match_threshold numeric(5,2)
    CHECK (match_threshold IS NULL OR match_threshold BETWEEN 0 AND 100);
CREATE UNIQUE INDEX IF NOT EXISTS alert_preference_id_uidx ON app.alert_preference (id);

CREATE TABLE IF NOT EXISTS app.application_status_event (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  application_id uuid NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
  job_id integer NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
  applicant_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  from_status text,
  to_status text NOT NULL,
  actor_id bigint REFERENCES public.users(id) ON DELETE SET NULL,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  CHECK (from_status IS NULL OR from_status <> to_status)
);

CREATE INDEX IF NOT EXISTS notification_unread_idx ON app.notification (user_id, created_at DESC) WHERE read_at IS NULL;
CREATE INDEX IF NOT EXISTS notification_expiry_idx ON app.notification (expires_at) WHERE expires_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS status_event_application_idx ON app.application_status_event (application_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS status_event_job_time_idx ON app.application_status_event (job_id, occurred_at DESC);

CREATE OR REPLACE FUNCTION app.application_status_event_trigger()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO app.application_status_event (application_id, job_id, applicant_id, from_status, to_status)
    VALUES (NEW.id, NEW.job_id, NEW.applicant_id,
            CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.status END, NEW.status);
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS application_status_event_trg ON public.applications;
CREATE TRIGGER application_status_event_trg AFTER INSERT OR UPDATE OF status
ON public.applications FOR EACH ROW EXECUTE FUNCTION app.application_status_event_trigger();

COMMIT;
