import React, { useState, useEffect, useCallback } from 'react';
import { useNavigate } from 'react-router-dom';
import { 
  Sparkles, 
  Compass, 
  Building, 
  MapPin, 
  ArrowRight, 
  Loader2, 
  FileText, 
  AlertCircle, 
  RotateCcw,
  CheckCircle2,
  Tag
} from 'lucide-react';
import Button from '../../../components/common/Button';
import Chip from '../../../components/common/Chip';
import recommendationService from '../../../services/recommendations';
import resumeService from '../../../services/resume';
import authService from '../../../services/auth';

export default function JobSeekerRecommendationsPage() {
  const navigate = useNavigate();
  const session = authService.getSession();
  const userId = session?.user?.user_id || session?.user?.id || 1;

  const [activeResume, setActiveResume] = useState(null);
  const [hasNoResume, setHasNoResume] = useState(false);
  const [recommendations, setRecommendations] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  // 1. Fetch live recommendations for candidate's resume
  const fetchRecommendations = useCallback(async (resumeId) => {
    setLoading(true);
    setError(null);

    try {
      const data = await recommendationService.getRecommendations(userId, resumeId, {
        limit: 10,
        include_ats: true,
      });
      setRecommendations(Array.isArray(data) ? data : []);
    } catch (err) {
      setRecommendations([]);
      if (err.status === 403) {
        setError('Access denied: Role recommendations require an authenticated Job Seeker account.');
      } else if (err.status === 401) {
        setError('Your session has expired. Please log in again to load career recommendations.');
      } else if (err.status === 400) {
        setError(err.message || 'Invalid recommendation request parameters.');
      } else if (err.status === 404) {
        setError('Resume profile not found. Please upload or activate a resume to view recommendations.');
      } else {
        setError(err.message || 'Recommendation service is currently unavailable. Please verify backend services are running.');
      }
    } finally {
      setLoading(false);
    }
  }, [userId]);

  // 2. Resolve candidate's active resume on mount
  useEffect(() => {
    let cachedResume = resumeService.getActiveResume();
    if (cachedResume?.resume_id) {
      setActiveResume(cachedResume);
      fetchRecommendations(cachedResume.resume_id);
      return;
    }

    // Fallback: query user's uploaded resumes from resumeService
    resumeService.listResumes()
      .then((data) => {
        const versions = Array.isArray(data?.versions) ? data.versions : [];
        if (versions.length > 0) {
          const selected = versions.find((v) => v.is_active) || versions[0];
          resumeService.setActiveResume(selected);
          setActiveResume(selected);
          fetchRecommendations(selected.resume_id || selected.version_id);
        } else {
          setHasNoResume(true);
          setLoading(false);
        }
      })
      .catch(() => {
        setHasNoResume(true);
        setLoading(false);
      });
  }, [fetchRecommendations]);

  return (
    <div className="space-y-6 animate-fadeIn pb-12">
      
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-outline-variant pb-4">
        <div>
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-purple-950/40 text-purple-300 border border-purple-800/40 text-xs font-semibold mb-2">
            <Sparkles className="w-3.5 h-3.5 text-purple-400" />
            <span>AI Career Intelligence • Milestone 3</span>
          </div>
          <h1 className="text-xl sm:text-2xl font-extrabold text-content">Curated Recommendations</h1>
          <p className="text-xs text-content-muted mt-1">
            Personalized role matches generated by aligning your verified capabilities with live requisitions.
          </p>
        </div>

        <div className="flex items-center gap-2">
          {activeResume && (
            <Button
              variant="tonal"
              size="sm"
              icon={FileText}
              onClick={() => navigate('/dashboard/job-seeker/resume')}
            >
              Resume Studio
            </Button>
          )}
          <Button
            variant="filled"
            size="sm"
            icon={Compass}
            onClick={() => navigate('/dashboard/job-seeker/discover')}
          >
            Open Swipe Deck
          </Button>
        </div>
      </div>

      {/* Main Viewport based on State */}
      {hasNoResume ? (
        /* Empty Resume State with clear CTA */
        <div className="surface-card p-12 text-center space-y-3 border border-dashed border-outline-variant">
          <FileText className="w-10 h-10 text-content-subtle mx-auto" />
          <h2 className="text-base font-bold text-content">No Resume Available</h2>
          <p className="text-xs text-content-muted max-w-sm mx-auto">
            To receive personalized career recommendations aligned with your experience and verified skills, please upload your resume.
          </p>
          <div className="pt-2">
            <Button
              variant="filled"
              size="sm"
              icon={FileText}
              onClick={() => navigate('/dashboard/job-seeker/resume')}
            >
              Upload Resume
            </Button>
          </div>
        </div>
      ) : loading ? (
        /* Loading State */
        <div className="py-20 text-center text-xs text-content-subtle space-y-3">
          <Loader2 className="w-7 h-7 animate-spin text-primary mx-auto" />
          <p className="font-medium text-content">Curating personalized career matches...</p>
          <p className="text-[11px] text-content-muted">Evaluating semantic similarity and ATS compatibility against active requisitions.</p>
        </div>
      ) : error ? (
        /* Error State with Retry CTA */
        <div className="surface-card p-8 text-center space-y-3 border border-red-800/40 bg-red-950/20">
          <AlertCircle className="w-8 h-8 text-red-400 mx-auto" />
          <h2 className="text-sm font-bold text-red-200">Unable to Load Recommendations</h2>
          <p className="text-xs text-red-300 max-w-md mx-auto">{error}</p>
          <div className="pt-2">
            <Button
              variant="tonal"
              size="sm"
              icon={RotateCcw}
              onClick={() => fetchRecommendations(activeResume?.resume_id || activeResume?.version_id)}
            >
              Retry Loading Recommendations
            </Button>
          </div>
        </div>
      ) : recommendations.length > 0 ? (
        /* Grid of Curated Recommended Jobs */
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {recommendations.map((job, idx) => {
            const rawScore = job.match_percentage ?? job.match_score;
            const matchScore = typeof rawScore === 'number' ? Math.round(rawScore > 1 ? rawScore : rawScore * 100) : null;
            const matchType = job.match_type;
            const atsScore = job.ats_score != null ? Math.round(job.ats_score) : null;
            const reasonTags = Array.isArray(job.reason_tags) ? job.reason_tags : [];

            return (
              <div
                key={job.id || job.job_id || idx}
                className="surface-card p-5 space-y-4 hover-card flex flex-col justify-between border border-outline-variant"
              >
                <div className="space-y-3">
                  {/* Top Match Metadata Strip */}
                  <div className="flex items-center justify-between gap-2 flex-wrap">
                    <div className="flex items-center gap-1.5 flex-wrap">
                      {matchScore !== null ? (
                        <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-lg text-xs font-semibold bg-surface-elevated text-primary border border-primary/30">
                          <Sparkles className="w-3 h-3 text-primary shrink-0" />
                          <span>{matchScore}% Match</span>
                        </span>
                      ) : (
                        <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-lg text-xs font-semibold bg-surface-elevated text-primary border border-primary/30">
                          <Sparkles className="w-3 h-3 text-primary shrink-0" />
                          <span>Recommended</span>
                        </span>
                      )}

                      {matchType && (
                        <span className="px-2 py-0.5 rounded-md text-[10px] font-mono uppercase bg-white/[0.04] text-content-subtle border border-white/[0.06]">
                          {matchType}
                        </span>
                      )}

                      {atsScore !== null && (
                        <span className="px-2 py-0.5 rounded-md text-[10px] font-semibold bg-emerald-950/40 text-emerald-300 border border-emerald-800/30">
                          ATS: {atsScore}%
                        </span>
                      )}
                    </div>

                    <span className="text-xs font-medium text-emerald-400 whitespace-nowrap">
                      {job.salary || 'Competitive'}
                    </span>
                  </div>

                  {/* Title & Organization */}
                  <div className="space-y-1">
                    <h3 className="text-base font-semibold text-content leading-tight truncate">
                      {job.title}
                    </h3>

                    <div className="flex items-center gap-2 text-xs text-content-muted flex-wrap">
                      <span className="flex items-center gap-1 min-w-0">
                        <Building className="w-3.5 h-3.5 text-content-subtle shrink-0" />
                        <span className="truncate max-w-[140px]">{job.company}</span>
                      </span>
                      <span>•</span>
                      <span className="flex items-center gap-1 min-w-0">
                        <MapPin className="w-3.5 h-3.5 text-content-subtle shrink-0" />
                        <span className="truncate max-w-[120px]">{job.location || 'Remote'}</span>
                      </span>
                    </div>
                  </div>

                  {/* Reason Tags */}
                  {reasonTags.length > 0 && (
                    <div className="p-2.5 rounded-xl bg-surface-elevated/60 border border-outline-variant space-y-1">
                      <div className="flex items-center gap-1 text-[10px] uppercase font-bold text-content-subtle tracking-wider">
                        <CheckCircle2 className="w-3 h-3 text-primary" />
                        <span>Match Insights</span>
                      </div>
                      <div className="flex flex-wrap gap-1.5">
                        {reasonTags.slice(0, 2).map((tag, tIdx) => (
                          <span key={tIdx} className="text-[11px] text-content-muted">
                            • {tag}
                          </span>
                        ))}
                      </div>
                    </div>
                  )}

                  {/* Skills Chips */}
                  {job.skills && (
                    <div className="flex flex-wrap gap-1 pt-0.5">
                      {(Array.isArray(job.skills) ? job.skills : []).slice(0, 4).map((s, sIdx) => (
                        <span key={sIdx} className="text-[10px] px-2 py-0.5 rounded-md bg-surface-elevated text-content-muted border border-outline-variant">
                          {s}
                        </span>
                      ))}
                    </div>
                  )}
                </div>

                <div className="pt-3 border-t border-outline-variant flex items-center justify-between gap-2">
                  <span className="text-[11px] text-content-subtle">
                    {matchType === 'semantic' ? 'Semantic sentence embedding fit' : 'Verified candidate capability match'}
                  </span>
                  <Button
                    variant="tonal"
                    size="sm"
                    icon={ArrowRight}
                    onClick={() => navigate('/dashboard/job-seeker/discover')}
                    className="w-full sm:w-auto"
                  >
                    View in Deck
                  </Button>
                </div>
              </div>
            );
          })}
        </div>
      ) : (
        /* Empty Recommendations State */
        <div className="surface-card p-12 text-center space-y-3 border-dashed border-outline-variant">
          <Sparkles className="w-10 h-10 text-content-subtle mx-auto" />
          <h2 className="text-base font-bold text-content">No recommendations generated yet</h2>
          <p className="text-xs text-content-muted max-w-sm mx-auto">
            Swipe through a few openings or adjust your resume skills to help the recommendation engine benchmark your preferences.
          </p>
          <div className="pt-2">
            <Button
              variant="filled"
              size="sm"
              icon={Compass}
              onClick={() => navigate('/dashboard/job-seeker/discover')}
            >
              Start Discovering
            </Button>
          </div>
        </div>
      )}

    </div>
  );
}
