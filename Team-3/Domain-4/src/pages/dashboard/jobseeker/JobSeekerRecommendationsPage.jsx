import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import { Sparkles, Compass, Building, MapPin, Banknote, ArrowRight, Loader2 } from 'lucide-react';
import Button from '../../../components/common/Button';
import Chip from '../../../components/common/Chip';
import recommendationService from '../../../services/recommendations';
import resumeService from '../../../services/resume';
import authService from '../../../services/auth';

export default function JobSeekerRecommendationsPage() {
  const navigate = useNavigate();
  const session = authService.getSession();
  const [recommendations, setRecommendations] = useState([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const resume = resumeService.getActiveResume();
    const userId = session?.user?.user_id || session?.user?.id || 1;
    const resumeId = resume?.resume_id;

    recommendationService.getRecommendations(userId, resumeId)
      .then((data) => setRecommendations(Array.isArray(data) ? data : []))
      .catch(() => setRecommendations([]))
      .finally(() => setLoading(false));
  }, []);

  return (
    <div className="space-y-6 animate-fadeIn">
      
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-outline-variant pb-4">
        <div>
          <div className="flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-purple-400" />
            <h1 className="text-xl sm:text-2xl font-extrabold text-content">Curated Recommendations</h1>
          </div>
          <p className="text-xs text-content-muted mt-1">
            Personalized role matches generated by aligning your verified capabilities with live requisitions.
          </p>
        </div>

        <Button
          variant="filled"
          size="sm"
          icon={Compass}
          onClick={() => navigate('/dashboard/job-seeker/discover')}
        >
          Open Swipe Deck
        </Button>
      </div>

      {/* Recommendations List */}
      {loading ? (
        <div className="py-16 text-center text-xs text-content-subtle space-y-2">
          <Loader2 className="w-6 h-6 animate-spin text-primary mx-auto" />
          <p>Curating personalized career matches...</p>
        </div>
      ) : recommendations.length > 0 ? (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {recommendations.map((job, idx) => {
            const rawScore = job.match_score ?? job.match_percentage;
            const matchScore = typeof rawScore === 'number'
              ? Math.round(rawScore > 1 ? rawScore : rawScore * 100)
              : 90 + (idx % 8);

            return (
              <div
                key={job.id || job.job_id || idx}
                className="surface-card p-5 space-y-3.5 hover-card flex flex-col justify-between"
              >
                <div className="space-y-2.5">
                  <div className="flex items-center justify-between gap-2">
                    <span className="inline-flex items-center px-2 py-0.5 rounded-md text-[11px] font-medium bg-primary-container/30 text-primary-onContainer border border-primary/20 whitespace-nowrap">
                      {matchScore}% Match
                    </span>
                    <span className="text-xs font-medium text-content whitespace-nowrap">
                      {job.salary || 'Competitive'}
                    </span>
                  </div>

                  <h3 className="text-base font-semibold text-content leading-tight truncate">
                    {job.title}
                  </h3>

                  <div className="flex items-center gap-2 text-xs text-content-muted flex-wrap">
                    <span className="flex items-center gap-1 min-w-0">
                      <Building className="w-3.5 h-3.5 text-content-subtle shrink-0" />
                      <span className="truncate max-w-[140px]">{job.company}</span>
                    </span>
                    <span>•</span>
                    <span className="flex items-center gap-1 min-w-0">
                      <MapPin className="w-3.5 h-3.5 text-content-subtle shrink-0" />
                      <span className="truncate max-w-[120px]">{job.location || 'Remote'}</span>
                    </span>
                  </div>

                  {job.skills && (
                    <div className="flex flex-wrap gap-1 pt-1">
                      {(Array.isArray(job.skills) ? job.skills : []).slice(0, 3).map((s, sIdx) => (
                        <span key={sIdx} className="text-[10px] px-2 py-0.5 rounded-md bg-surface-elevated text-content-muted border border-outline-variant">
                          {s}
                        </span>
                      ))}
                    </div>
                  )}
                </div>

                <div className="pt-3 border-t border-outline-variant flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                  <span className="text-[11px] text-content-subtle">
                    Verified skill match
                  </span>
                  <Button
                    variant="tonal"
                    size="sm"
                    icon={ArrowRight}
                    onClick={() => navigate('/dashboard/job-seeker/discover')}
                    className="w-full sm:w-auto"
                  >
                    View in Deck
                  </Button>
                </div>
              </div>
            );
          })}
        </div>
      ) : (
        <div className="surface-card p-12 text-center space-y-3 border-dashed">
          <Sparkles className="w-10 h-10 text-content-subtle mx-auto" />
          <h2 className="text-base font-bold text-content">No recommendations generated yet</h2>
          <p className="text-xs text-content-muted max-w-sm mx-auto">
            Upload your resume or swipe through a few openings to help the recommendation engine benchmark your preferences.
          </p>
          <div className="pt-2">
            <Button
              variant="filled"
              size="sm"
              icon={Compass}
              onClick={() => navigate('/dashboard/job-seeker/discover')}
            >
              Start Discovering
            </Button>
          </div>
        </div>
      )}

    </div>
  );
}
