-- Minimal Domain 2-owned tables matching the shared service column types.
-- Domain 1's managed migrations create users/resumes/resume_versions first.
CREATE TABLE public.companies (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  company_type text NOT NULL
);

CREATE TABLE public.jobs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id integer NOT NULL REFERENCES public.companies(id),
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  employment_type text NOT NULL DEFAULT 'Full-time',
  location text NOT NULL DEFAULT 'Remote',
  is_remote boolean NOT NULL DEFAULT false,
  salary_min integer,
  salary_max integer,
  skills text NOT NULL DEFAULT '',
  experience_level text NOT NULL DEFAULT 'Fresher',
  applicant_count integer NOT NULL DEFAULT 0,
  posted_at timestamptz NOT NULL DEFAULT now()
);

